import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../../', import.meta.url));
const read = path => readFileSync(resolve(root, path), 'utf8');
const copies = JSON.parse(read('scripts/support/passkey-copy.json'));
const sources = [
  ['Google · iPhone', 'https://support.google.com/chrome/answer/13168025?co=GENIE.Platform%3DiOS'],
  ['Google · Android', 'https://developers.google.com/identity/passkeys/supported-environments'],
  ['Apple', 'https://support.apple.com/guide/iphone/use-passkeys-to-sign-in-to-apps-and-websites-iphf538ea8d0/ios'],
  ['Apple ↔ Google', 'https://support.google.com/chrome/answer/13068232?co=GENIE.Platform%3DiOS'],
];
const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const copy = copies.en;
const section = `<!-- passkey-guide:start -->
<section id="section-1" lang="en" dir="ltr" aria-labelledby="passkey-guide-title">
<h2 id="passkey-guide-title">${escape(copy.title)}</h2>
<p>${escape(copy.intro)}</p><p class="note">${escape(copy.safety)}</p>
${Object.entries(copy.scenarios).map(([id, scenario], index) => `<details class="gys-passkey-case" id="passkey-${id}"${index === 0 ? ' open' : ''}><summary>${escape(scenario.title)}</summary><ol>${scenario.steps.map(step => `<li>${escape(step)}</li>`).join('')}</ol></details>`).join('\n')}
<p><a href="#contact">${escape(copy.contact)}</a></p>
<p>${escape(copy.source)}: ${sources.map(([label, href]) => `<a href="${escape(href)}" rel="noopener noreferrer">${escape(label)}</a>`).join(' · ')}</p>
</section>
<!-- passkey-guide:end -->`;
const javascript = `// Generated by scripts/support/generate-passkey-guide.mjs. Edit the source catalog/runtime.\nconst PASSKEY_SUPPORT_COPY = ${JSON.stringify(copies)};\nconst PASSKEY_SUPPORT_SOURCES = ${JSON.stringify(sources)};\n${read('scripts/support/passkey-guide-runtime.js')}`;
const css = `/* Shared by both support hosts. */
#section-1, .gys-passkey-case { scroll-margin-top: 110px; }
#section-1 { overflow-wrap: anywhere; }
#section-1 .gys-passkey-case { border: 1px solid #39332c; border-radius: 12px; margin-block: 12px; padding: 0 16px; }
#section-1 summary { cursor: pointer; min-height: 44px; padding-block: 14px; font-weight: 650; color: #f5f0e8; }
#section-1 summary:focus-visible { outline: 2px solid #f7931a; outline-offset: 4px; }
#section-1 ol { padding-inline-start: 24px; margin-block: 4px 18px; }
#section-1 li { padding-inline-start: 4px; margin-block: 12px; line-height: 1.7; }
#section-1[dir="rtl"] { text-align: right; }
@media print { #section-1 details > * { display: block !important; } }
`;
let changed = false;
function output(path, content) {
  let previous; try { previous = read(path); } catch { /* New file. */ }
  if (previous === content) return;
  changed = true;
  if (process.argv.includes('--check')) { console.error(`Outdated generated support file: ${path}`); return; }
  writeFileSync(resolve(root, path), content);
}
for (const host of ['site', 'public']) {
  let html = read(`${host}/support.html`);
  const marker = /<!-- passkey-guide:start -->[\s\S]*?<!-- passkey-guide:end -->/;
  if (marker.test(html)) html = html.replace(marker, section);
  else {
    const old = /<h2 id="section-1">[\s\S]*?(?=<h2 id="section-3">)/;
    if (!old.test(html)) throw new Error(`Missing recovery section in ${host}`);
    html = html.replace(old, section + '\n');
  }
  if (!html.includes('/passkey-guide.js?v=1')) {
    html = html.replace('</head>', '<link rel="stylesheet" href="/passkey-guide.css?v=1"><script src="/passkey-guide.js?v=1" defer></script></head>');
  }
  output(`${host}/support.html`, html);
  output(`${host}/passkey-guide.js`, javascript);
  output(`${host}/passkey-guide.css`, css);
}
if (process.argv.includes('--check') && changed) process.exitCode = 1;
